//! Fixed, level-parametric syntax for universe composition's line equivalence.
//! This emits a data definition, not an unchecked typing assertion.
//!
//! For a line `P : Path U A B`, the equivalence is the transport `f` along
//! `P`, made an equivalence by `iso-equiv` with the transport `g` back along
//! `P` and two squares built by composition:
//!
//! ```text
//! f x = transp^i P(i) x            g y = transp^i P(~i) y
//! s y = <k> comp^i P(i)  [k=1 ↦ comp^m P(~m ∨ i)  [i=1 ↦ y] y] (g y)
//! t x = <k> comp^i P(~i) [k=1 ↦ comp^m P(m ∧ ~i) [i=1 ↦ x] x] (f x)
//! ```
//!
//! The center of the fiber of `f` over `y` is `(g y, s y)`, so composition
//! in the universe followed by Glue composition computes with one transport
//! back along the line, instead of transporting the identity equivalence's
//! contractibility evidence along it.
use crate::cubical::engine::iso_equiv_frontend::{iso_equiv_term, iso_equiv_type};
use crate::cubical::engine::path_frontend::{dim, papp, v};
use crate::cubical::engine::restricted_frontend::RestrictedProducer;
use crate::cubical::engine::term::{Result, Sexp, atom, call};
use crate::cubical::engine::transport_equiv_frontend::transport_equiv_type;
use crate::cubical::engine::transport_frontend::transport_at;

fn at1(k: usize) -> Sexp {
    call("at1", [crate::cubical::engine::term::numeral(k)])
}
fn one_side(phi: Sexp, t: Sexp) -> Sexp {
    call("system", [call("side", [phi, t, atom("snil")])])
}
fn app(f: Sexp, x: Sexp) -> Sexp {
    call("app", [f, x])
}

/// The program body in context `P, B, A` (v0, v1, v2) at level `l`.
pub fn line_equiv(p: &mut RestrictedProducer, l: usize) -> Result<Sexp> {
    let neg = |r: Sexp| call("neg", [r]);
    // Under λx (or λy): the line P is v1.
    let forward = transport_at(v(1), v(0));
    let backward = call(
        "comp",
        [papp(v(1), neg(dim(0))), atom("ff"), atom("zero"), v(0)],
    );
    // Under λy, <k>, then comp binder i (dim 0) with k at dim 1; the inner
    // composition binds m (dim 0) with i, k at dims 1, 2.
    let back_fill = call(
        "comp",
        [
            papp(v(1), call("join", [neg(dim(0)), dim(1)])),
            at1(0),
            one_side(at1(1), v(0)),
            v(0),
        ],
    );
    let section = call(
        "lam",
        [call(
            "plam",
            [call(
                "comp",
                [
                    papp(v(1), dim(0)),
                    at1(0),
                    one_side(at1(1), back_fill),
                    backward.clone(),
                ],
            )],
        )],
    );
    let forward_fill = call(
        "comp",
        [
            papp(v(1), call("meet", [dim(0), neg(dim(1))])),
            at1(0),
            one_side(at1(1), v(0)),
            v(0),
        ],
    );
    let retraction = call(
        "lam",
        [call(
            "plam",
            [call(
                "comp",
                [
                    papp(v(1), neg(dim(0))),
                    at1(0),
                    one_side(at1(1), forward_fill),
                    forward.clone(),
                ],
            )],
        )],
    );
    let (f, g) = (call("lam", [forward]), call("lam", [backward]));
    let iso = call("ann", [iso_equiv_term(p, l, l)?, iso_equiv_type(p, l, l)?]);
    let evidence = [v(2), v(1), f.clone(), g, section, retraction]
        .into_iter()
        .fold(iso, app);
    Ok(call("pair", [f, evidence]))
}

pub fn program(l: usize) -> Result<Sexp> {
    let mut p = RestrictedProducer::default();
    let body = line_equiv(&mut p, l)?;
    let term = (0..3).fold(body, |t, _| call("lam", [t]));
    let ty = transport_equiv_type(&mut p, l)?;
    Ok(call("ann", [term, ty]))
}
fn generalize(t: &Sexp) -> Sexp {
    if let Sexp::List(xs) = t {
        if xs.len() == 2 && xs[0] == atom("u") {
            fn offset(n: &Sexp) -> Sexp {
                if *n == atom("z") {
                    atom("?l")
                } else {
                    let Sexp::List(xs) = n else { unreachable!() };
                    call("s", [offset(&xs[1])])
                }
            }
            return call("u", [offset(&xs[1])]);
        }
        Sexp::List(xs.iter().map(generalize).collect())
    } else {
        t.clone()
    }
}
/// The text of `theories/cubical/canonical-map.horn`.
pub fn definition() -> Result<String> {
    let template = generalize(&program(0)?);
    Ok(format!(
        "; A syntactic program definition. Every use still checks its typing.\n; Generated by canonical_code_frontend::definition (see its documentation);\n; a test compares it with this file and checks its typing at levels 0, 1, 2.\n(pred canonical-map (N Tm))\n(rule def.canonical-map () (canonical-map ?l {template}))\n"
    ))
}
